import 'dart:io';
import 'dart:isolate';
import 'package:yaml/yaml.dart';

const wrapper = 'flutter_zoom_videosdk';
const targetPath = '.nosmai_zoom/flutter_zoom_videosdk';
const marker = '.nosmai-zoom-2.6.0-adapter-1';

Future<void> main() async {
  try {
    await install();
  } catch (error) {
    stderr.writeln(error);
    exitCode = 1;
  }
}

Future<void> install() async {
  final app = File('pubspec.yaml');
  if (!app.existsSync())
    throw StateError('Run setup from the Flutter app directory.');
  final appText = app.readAsStringSync();
  final supplemental = File('pubspec_overrides.yaml');
  final supplementalText =
      supplemental.existsSync() ? supplemental.readAsStringSync() : '';
  // Creating a second dependency_overrides section would shadow the app's
  // existing overrides, including future changes to local plugin paths.
  final overrides =
      usesMainOverrides(appText, supplementalText) ? app : supplemental;
  final original = overrides.existsSync() ? overrides.readAsStringSync() : '';
  final updated = overrideText(original);
  final dest = Directory(targetPath);
  if (!File('${dest.path}/$marker').existsSync()) {
    if (dest.existsSync())
      throw StateError(
          '$targetPath already exists. Choose a clean adapter location.');
    final entry = await Isolate.resolvePackageUri(
        Uri.parse('package:flutter_zoom_videosdk/native/zoom_videosdk.dart'));
    final bridge = await Isolate.resolvePackageUri(
        Uri.parse('package:nosmai_zoom_bridge/nosmai_zoom_bridge.dart'));
    if (entry == null || bridge == null)
      throw StateError('Run flutter pub get first.');
    final source = File.fromUri(entry).parent.parent.parent;
    final spec =
        loadYaml(File('${source.path}/pubspec.yaml').readAsStringSync());
    if (spec['version'] != '2.6.0')
      throw StateError('This adapter requires flutter_zoom_videosdk 2.6.0.');
    final patch = File.fromUri(bridge.resolve('../tool/zoom-2.6.0.patch'));
    await dest.parent.create(recursive: true);
    final stage = await dest.parent.createTemp('setup-');
    try {
      for (final name in ['lib', 'android', 'ios']) {
        copyTree(Directory('${source.path}/$name'),
            Directory('${stage.path}/$name'));
      }
      for (final name in [
        'pubspec.yaml',
        'LICENSE',
        'README.md',
        'CHANGELOG.md'
      ]) {
        File('${source.path}/$name').copySync('${stage.path}/$name');
      }
      final result = await Process.run(
          'patch', ['-s', '-f', '-p1', '-i', patch.absolute.path],
          workingDirectory: stage.path);
      if (result.exitCode != 0)
        throw StateError(
            'Zoom adapter patch failed. Check the upstream 2.6.0 source.\n${result.stderr}${result.stdout}');
      File('${stage.path}/$marker')
          .writeAsStringSync('Generated by nosmai_zoom_bridge.\n');
      await stage.rename(dest.path);
    } finally {
      if (stage.existsSync()) await stage.delete(recursive: true);
    }
  }
  if (original != updated) {
    // Write beside the destination so rename is atomic on the app filesystem.
    final temp = File('${overrides.path}.${pid}.tmp');
    try {
      temp.writeAsStringSync(updated, flush: true);
      temp.renameSync(overrides.path);
    } finally {
      if (temp.existsSync()) temp.deleteSync();
    }
  }
  stdout.writeln(
      'Zoom camera adapter ready. Run flutter pub get and rebuild the app.');
}

void copyTree(Directory from, Directory to) {
  to.createSync();
  for (final item in from.listSync(followLinks: false)) {
    final name = item.uri.pathSegments.where((v) => v.isNotEmpty).last;
    if (name.startsWith('.') ||
        const {'build', 'Pods', 'local.properties'}.contains(name)) continue;
    final path = '${to.path}/$name';
    if (item is Directory) copyTree(item, Directory(path));
    if (item is File) item.copySync(path);
  }
}

bool usesMainOverrides(String main, String supplemental) {
  final root = loadYaml(main);
  final extra = loadYaml(supplemental);
  return root is Map &&
      root.containsKey('dependency_overrides') &&
      !(extra is Map && extra.containsKey('dependency_overrides'));
}

String overrideText(String text) {
  final yaml = loadYaml(text);
  if (yaml != null && yaml is! YamlMap)
    throw StateError('Invalid pubspec_overrides.yaml.');
  final entries = yaml?['dependency_overrides'];
  if (entries != null && entries is! YamlMap)
    throw StateError('Unsupported dependency_overrides format.');
  final prior = entries?[wrapper];
  if (prior is Map && prior['path'] == targetPath) return text;
  if (prior != null)
    throw StateError(
        'An existing flutter_zoom_videosdk override needs to be resolved first.');
  final block =
      RegExp(r'^dependency_overrides:[ \t]*(?:#[^\n]*)?$', multiLine: true)
          .firstMatch(text);
  String output;
  if (block == null) {
    if (yaml is Map && yaml.containsKey('dependency_overrides')) {
      throw StateError('Use a YAML block mapping for dependency_overrides.');
    }
    output =
        '$text${text.isEmpty || text.endsWith('\n') ? '' : '\n'}dependency_overrides:\n  $wrapper:\n    path: $targetPath\n';
  } else {
    final after = text.substring(block.end);
    final firstChild =
        RegExp(r'^([ ]+)[^\s#]', multiLine: true).firstMatch(after);
    final indent = entries is Map && entries.isNotEmpty
        ? firstChild?.group(1) ?? '  '
        : '  ';
    output = text.replaceRange(
        block.end, block.end, '\n$indent$wrapper:\n$indent  path: $targetPath');
  }
  if (loadYaml(output)['dependency_overrides'][wrapper]['path'] != targetPath) {
    throw StateError('Could not safely update pubspec_overrides.yaml.');
  }
  return output;
}
